#!/usr/bin/env python3
"""Embed modules/control/wlc/ui/*.html into wlc_ui.h (run after editing the UI)."""
import os
here = os.path.dirname(os.path.abspath(__file__))
ui = os.path.join(here, '..', 'modules', 'control', 'wlc', 'ui')
dst = os.path.join(here, '..', 'modules', 'control', 'wlc', 'wlc_ui.h')
out = ['/* Generated by tools-wlc/gen_ui.py from the ui folder - do not edit. */',
       '#ifndef WLC_UI_H', '#define WLC_UI_H', '#include <stddef.h>']
for src, var in (('index.html', 'wlc_ui_html'), ('screen.html', 'wlc_screen_html')):
    data = open(os.path.join(ui, src), 'rb').read()
    out.append('static const unsigned char %s[] = {' % var)
    for i in range(0, len(data), 20):
        out.append(' ' + ','.join(str(b) for b in data[i:i+20]) + ',')
    out += ['};', 'static const size_t %s_len = %d;' % (var, len(data))]
    print('%s: %d bytes embedded as %s' % (src, len(data), var))
out += ['#endif', '']
open(dst, 'w').write('\n'.join(out))
